// Writes native/generated/params.h: each machine's parameter positions, taken
// from the TypeScript definitions, so the C++ and TypeScript engines always
// agree on which value is which. Run with: npm run native:params
import { writeFileSync } from "node:fs";
const { MACHINES } = await import("../src/machines/index.ts");
const ident = (s) => s.replace(/[^A-Za-z0-9]/g, "_");
let out = `// Generated by tools/gen-native-params.mjs from src/machines. Do not edit.\n#pragma once\nnamespace soundlab::params {\n`;
for (const m of MACHINES) {
  out += `// ${m.name} (${m.id})\nnamespace ${ident(m.id).replace(/_/g, "")} {\n  enum : int {\n`;
  m.params.forEach((d, i) => (out += `    ${ident(d.id)} = ${i},\n`));
  out += `    COUNT = ${m.params.length}\n  };\n}\n`;
}
out += `} // namespace soundlab::params\n`;
writeFileSync(new URL("../native/generated/params.h", import.meta.url), out);
console.log(`Wrote params for ${MACHINES.length} machines.`);
