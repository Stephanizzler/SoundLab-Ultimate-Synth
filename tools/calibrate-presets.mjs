// Sets every preset's patch level so presets sit at the loudness of their
// role (ROLE_TARGETS), and writes src/machines/preset-trims.ts. Run it after
// adding or changing presets:  node tools/calibrate-presets.mjs [machine-id …]
import { readFileSync, writeFileSync } from "node:fs";
import { auditPresets, ROLE_TARGETS, PEAK_CAP } from "./preset-audit.mjs";

const FILE = new URL("../src/machines/preset-trims.ts", import.meta.url);
const only = process.argv.slice(2);
const old = (() => { try { return JSON.parse(readFileSync(FILE, "utf8").match(/= (\{[\s\S]*\});/)[1]); } catch { return {}; } })();
const rows = await auditPresets({ trims: false, only: only.length ? only : undefined });
const trims = only.length ? old : {};
for (const r of rows) {
  if (r.lufs == null) { console.warn(`${r.machine} · ${r.preset}: silent`); continue; }
  // Very percussive sounds would need so much gain to reach the target that
  // their attack would clip; those stop at a peak of PEAK_CAP.
  const want = Math.round((ROLE_TARGETS[r.role] - r.lufs) * 2) / 2, cap = Math.floor(20 * Math.log10(PEAK_CAP / r.peak) * 2) / 2;
  const t = Math.min(want, cap);
  if (t < want) console.warn(`${r.machine} · ${r.preset}: peak-limited at ${t} dB (wanted ${want})`);
  if (t > 18 || t < -30) console.warn(`${r.machine} · ${r.preset}: needs ${t} dB, outside the patch level range`);
  (trims[r.id] ??= {})[r.preset] = Math.max(-30, Math.min(18, t));
  console.log(`${r.machine.padEnd(18)} ${r.preset.padEnd(28)} ${r.role.padEnd(8)} ${String(r.lufs).padStart(6)} → ${t > 0 ? "+" : ""}${t} dB`);
}
writeFileSync(FILE, `// Generated by tools/calibrate-presets.mjs: each preset's patch level in dB,
// so presets of one role (bass, pad, ...) play at about the same loudness.
export const PRESET_TRIMS: Record<string, Record<string, number>> = ${JSON.stringify(trims, null, 2)};
`);
