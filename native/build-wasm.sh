#!/usr/bin/env bash
# Builds native/dist/soundlab.wasm with clang's WebAssembly target (no
# Emscripten needed), then embeds it in src/engine/native-wasm.ts for the app.
set -euo pipefail
cd "$(dirname "$0")"
clang++ --target=wasm32 -std=c++17 -O3 -nostdlib -fno-exceptions -fno-rtti -ffp-contract=off \
  -Iinclude -Wall -Wextra \
  -Wl,--no-entry -Wl,--allow-undefined -Wl,--strip-all \
  -o dist/soundlab.wasm src/wasm_api.cpp
node -e '
const fs = require("fs");
const b64 = fs.readFileSync("dist/soundlab.wasm").toString("base64");
fs.writeFileSync("../src/engine/native-wasm.ts", "// Generated by native/build-wasm.sh from native/: the C++ audio core as WebAssembly. Do not edit.\nexport const NATIVE_WASM_BASE64 = \"" + b64 + "\";\n");
console.log("soundlab.wasm:", fs.statSync("dist/soundlab.wasm").size, "bytes");
'
